import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import test from "node:test";
import { Client, Pool } from "pg";
import dotenv from "dotenv";
import { betterAuth } from "better-auth";
import { admin } from "better-auth/plugins";
import { SignJWT } from "jose";
import { loadSource } from "./auth-source.mjs";

dotenv.config({ path: ".env.local", quiet: true });
dotenv.config({ path: ".env", quiet: true });
const connectionString = process.env.AUTH_TEST_DATABASE_URL || (process.env.BETTER_AUTH_URL?.startsWith("http://localhost:") ? process.env.DATABASE_URL : undefined);
const { accountAuthOptions } = loadSource("src/lib/auth-options.ts", { "better-auth/plugins": { admin } });
const baseURL = "http://localhost:3000";
const secret = "disposable-auth-fixture-secret-at-least-32-characters";
const password = "a new secure passphrase";

test("native Better Auth recovery, verification, roles, rollback and database throttling", { skip: !connectionString, timeout: 120000 }, async t => {
  const schema = "auth_email_fixture_" + randomUUID().replaceAll("-", "");
  assert(/^auth_email_fixture_[0-9a-f]{32}$/.test(schema));
  const setup = new Client({ connectionString }); await setup.connect();
  let pool;
  try {
    await setup.query(`CREATE SCHEMA "${schema}"`);
    for (const table of ["user", "account", "session", "verification"]) await setup.query(`CREATE TABLE "${schema}"."${table}" (LIKE public."${table}" INCLUDING ALL)`);
    await setup.query(`SET search_path TO "${schema}"`);
    await setup.query(readFileSync(new URL("../drizzle/0003_auth_rate_limits.sql", import.meta.url), "utf8").replace("--> statement-breakpoint", ""));
    pool = new Pool({ connectionString, options: `-c search_path=${schema}`, max: 12 });
    const mails = [];
    const options = accountAuthOptions(pool, baseURL, secret, message => mails.push(message));
    const auth = betterAuth({ ...options, logger: { disabled: true } });
    let ipNumber = 0;
    async function request(path, body, { cookie, ip = `198.51.${Math.floor(++ipNumber / 250)}.${ipNumber % 250 + 1}`, origin = baseURL, method = body ? "POST" : "GET" } = {}) {
      const headers = new Headers({ Origin: origin, "x-forwarded-for": ip });
      if (body) headers.set("Content-Type", "application/json");
      if (cookie) headers.set("Cookie", cookie);
      const response = await auth.handler(new Request(path.startsWith("http") ? path : baseURL + "/api/auth" + path, { method, headers, body: body ? JSON.stringify(body) : undefined }));
      const setCookies = response.headers.getSetCookie();
      const content = await response.text();
      let json; try { json = JSON.parse(content); } catch { json = null; }
      return { status: response.status, json, headers: response.headers, cookie: setCookies.map(c => c.split(";")[0]).join("; ") };
    }
    async function login(email, loginPassword = "short123") {
      return request("/sign-in/email", { email, password: loginPassword });
    }
    async function session(cookie) { return request("/get-session", undefined, { cookie }); }
    async function resetToken(email, adminContext = false) {
      const result = await request("/request-password-reset", { email, redirectTo: baseURL + (adminContext ? "/admin/reset-password" : "/reset-password") });
      assert.equal(result.status, 200);
      const mail = mails.filter(m => m.kind === "reset" && m.email === email).at(-1);
      return new URL(mail.url).pathname.split("/").at(-1);
    }
    // Disposable fixture hash generated by the original Better Auth 1.7.5.
    const existingHash = "9f57b08d33be30748dc0ffc5f51e1daa:276d72f47df15cac7758397f1a81a178183d4e773369ef08791c0d205a6c719ab1ade605dbc340fad9875297ce472933a3ff8ec74512c067800fc4a233690eaf";
    for (const [id, role] of [["legacy-buyer", "user"], ["legacy-admin", "admin"], ["rollback-buyer", "user"]]) {
      await pool.query('INSERT INTO "user" (id,name,email,"emailVerified",role,"createdAt","updatedAt") VALUES ($1,$1,$2,false,$3,now(),now())', [id, id + "@example.invalid", role]);
      await pool.query('INSERT INTO "account" (id,"accountId","providerId","userId",password,"createdAt","updatedAt") VALUES ($1,$1,\'credential\',$1,$2,now(),now())', [id, existingHash]);
    }

    await t.test("existing short-password buyers and admins retain roles, hashes and unverified login access", async () => {
      const before = mails.length;
      for (const [id, role] of [["legacy-buyer", "user"], ["legacy-admin", "admin"]]) {
        const signedIn = await login(id + "@example.invalid"); assert.equal(signedIn.status, 200);
        assert.equal(signedIn.json.user.role, role); assert.equal(signedIn.json.user.emailVerified, false);
        assert.equal((await session(signedIn.cookie)).json.user.role, role);
        assert.equal((await pool.query('SELECT password FROM "account" WHERE id=$1', [id])).rows[0].password, existingHash);
      }
      assert.equal(mails.length, before);
      assert.equal((await request("/change-password", { currentPassword: "short123", newPassword: password })).status, 401);
      assert.equal((await request("/sign-up/email", { name: "Attack", email: "csrf@example.invalid", password }, { origin: "https://evil.invalid" })).status, 403);
    });

    let signup;
    await t.test("registration enforces new password bounds, rejects role injection and signs buyer in while queuing verification", async () => {
      for (const value of ["short123", "x".repeat(129)]) assert.equal((await request("/sign-up/email", { name: "Fixture", email: "invalid@example.invalid", password: value })).status, 400);
      const injection = await request("/sign-up/email", { name: "New fixture", email: "new@example.invalid", password, role: "admin", emailVerified: true });
      assert.equal(injection.status, 400);
      signup = await request("/sign-up/email", { name: "New fixture", email: "new@example.invalid", password, callbackURL: baseURL + "/verify-email/callback" });
      assert.equal(signup.status, 200); assert(signup.cookie);
      assert.equal(signup.json.user.role, "user"); assert.equal(signup.json.user.emailVerified, false);
      assert.equal((await session(signup.cookie)).json.user.role, "user");
      assert.equal((await request("/admin/create-user", { name: "Injected admin", email: "admin-injection@example.invalid", password, role: "admin" })).status, 401);
      assert.equal((await request("/admin/create-user", { name: "Injected admin", email: "admin-injection@example.invalid", password, role: "admin" }, { cookie: signup.cookie })).status, 403);
      const mail = mails.find(m => m.kind === "verification" && m.email === "new@example.invalid"); assert(mail);
      const url = new URL(mail.url); assert.equal(url.searchParams.get("callbackURL"), baseURL + "/verify-email/callback");
      const claims = JSON.parse(Buffer.from(url.searchParams.get("token").split(".")[1], "base64url").toString());
      assert.equal(claims.exp - claims.iat, 86400);
      const roleUpdate = await request("/update-user", { role: "admin", emailVerified: true }, { cookie: signup.cookie });
      assert([200, 400].includes(roleUpdate.status));
      assert.equal((await session(signup.cookie)).json.user.role, "user");
      assert.equal((await session(signup.cookie)).json.user.emailVerified, false);
    });

    await t.test("recovery is generic; valid reset revokes every session, invalidates old password and preserves role", async () => {
      const known = await request("/request-password-reset", { email: "legacy-admin@example.invalid", redirectTo: baseURL + "/admin/reset-password" });
      const unknown = await request("/request-password-reset", { email: "unknown@example.invalid", redirectTo: baseURL + "/admin/reset-password" });
      assert.equal(known.status, unknown.status); assert.deepEqual(known.json, unknown.json);
      const token = await resetToken("legacy-admin@example.invalid", true);
      const expires = (await pool.query('SELECT "expiresAt" FROM verification WHERE identifier=$1', ["reset-password:" + token])).rows[0].expiresAt;
      assert(Math.abs(expires.getTime() - Date.now() - 1800000) < 5000);
      const mail = mails.filter(m => m.kind === "reset").at(-1);
      const callback = await request(mail.url); assert.equal(callback.status, 302);
      assert.equal(new URL(callback.headers.get("location")).pathname, "/admin/reset-password");
      const first = await login("legacy-admin@example.invalid"), second = await login("legacy-admin@example.invalid");
      const reset = await request("/reset-password", { token, newPassword: password }); assert.equal(reset.status, 200); assert.equal(reset.cookie, "");
      assert.equal((await session(first.cookie)).json, null); assert.equal((await session(second.cookie)).json, null);
      assert.equal((await login("legacy-admin@example.invalid")).status, 401);
      assert.equal((await login("legacy-admin@example.invalid", password)).json.user.role, "admin");
      assert.equal((await request("/reset-password", { token, newPassword: password })).status, 400);
    });

    await t.test("missing, invalid, expired and concurrently redeemed reset tokens fail safely", async () => {
      for (const token of [undefined, "invalid-token"]) assert.equal((await request("/reset-password", { token, newPassword: password })).status, 400);
      const expired = await resetToken("legacy-buyer@example.invalid");
      await pool.query('UPDATE verification SET "expiresAt"=now()-interval \'1 minute\' WHERE identifier=$1', ["reset-password:" + expired]);
      assert.equal((await request("/reset-password", { token: expired, newPassword: password })).status, 400);
      const mail = mails.filter(m => m.kind === "reset").at(-1);
      const callback = await request(mail.url); assert.equal(new URL(callback.headers.get("location")).searchParams.get("error"), "INVALID_TOKEN");
      const token = await resetToken("legacy-buyer@example.invalid");
      assert.equal((await request("/reset-password", { token, newPassword: "short" })).status, 400);
      const results = await Promise.all(Array.from({ length: 4 }, () => request("/reset-password", { token, newPassword: password })));
      assert.deepEqual(results.map(r => r.status).sort(), [200, 400, 400, 400]);
    });

    await t.test("reset and change transactions restore tokens, passwords and sessions after password or revocation failures", async () => {
      const signedIn = await login("rollback-buyer@example.invalid");
      const token = await resetToken("rollback-buyer@example.invalid");
      await pool.query(`CREATE FUNCTION fixture_failure() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'fixture failure'; END; $$`);
      for (const [table, action] of [["account", "UPDATE"], ["session", "DELETE"]]) {
        await pool.query(`CREATE TRIGGER fixture_failure BEFORE ${action} ON "${table}" FOR EACH ROW EXECUTE FUNCTION fixture_failure()`);
        for (const operation of [() => request("/reset-password", { token, newPassword: password }), () => request("/change-password", { currentPassword: "short123", newPassword: password, revokeOtherSessions: true }, { cookie: signedIn.cookie })]) {
          const previousError = console.error;
          let failure;
          try { console.error = () => {}; failure = await operation(); }
          finally { console.error = previousError; }
          assert.equal(failure.status, 500);
          assert.equal((await pool.query('SELECT password FROM account WHERE id=\'rollback-buyer\'')).rows[0].password, existingHash);
          assert.equal((await pool.query('SELECT count(*) FROM verification WHERE identifier=$1', ["reset-password:" + token])).rows[0].count, "1");
          assert((await session(signedIn.cookie)).json);
        }
        await pool.query(`DROP TRIGGER fixture_failure ON "${table}"`);
      }
      assert.equal((await request("/reset-password", { token, newPassword: password })).status, 200);
    });

    await t.test("password changes require current password, preserve current login and optionally revoke other sessions; logout invalidates session", async () => {
      let first = await login("new@example.invalid", password); const second = await login("new@example.invalid", password);
      assert.equal((await request("/change-password", { currentPassword: "wrong", newPassword: "a second secure passphrase", revokeOtherSessions: true }, { cookie: first.cookie })).status, 400);
      const kept = await request("/change-password", { currentPassword: password, newPassword: "a second secure passphrase", revokeOtherSessions: false }, { cookie: first.cookie }); assert.equal(kept.status, 200);
      assert((await session(first.cookie)).json); assert((await session(second.cookie)).json);
      assert.equal((await login("new@example.invalid", password)).status, 401);
      const changed = await request("/change-password", { currentPassword: "a second secure passphrase", newPassword: "a third secure passphrase", revokeOtherSessions: true }, { cookie: first.cookie }); assert.equal(changed.status, 200);
      assert.equal((await session(second.cookie)).json, null); assert.equal((await session(first.cookie)).json, null);
      first = changed; assert((await session(first.cookie)).json);
      assert.equal((await request("/sign-out", {}, { cookie: first.cookie })).status, 200);
      assert.equal((await session(first.cookie)).json, null);
    });

    await t.test("verification resend is generic; expiry, verification and replay route safely without automatic signin", async () => {
      const count = mails.length;
      const known = await request("/send-verification-email", { email: "new@example.invalid", callbackURL: baseURL + "/verify-email/callback" });
      const unknown = await request("/send-verification-email", { email: "unknown@example.invalid", callbackURL: baseURL + "/verify-email/callback" });
      assert.equal(known.status, 200); assert.deepEqual(known.json, unknown.json); assert.equal(mails.length, count + 1);
      const mail = mails.at(-1);
      for (let attempt = 0; attempt < 2; attempt++) {
        const result = await request(mail.url); assert.equal(result.status, 302);
        assert.equal(new URL(result.headers.get("location")).pathname, "/verify-email/callback"); assert.equal(result.cookie, "");
      }
      assert.equal((await pool.query('SELECT "emailVerified" FROM "user" WHERE email=\'new@example.invalid\'')).rows[0].emailVerified, true);
      const expired = await new SignJWT({ email: "legacy-buyer@example.invalid" }).setProtectedHeader({ alg: "HS256" }).setIssuedAt().setExpirationTime(Math.floor(Date.now() / 1000) - 60).sign(new TextEncoder().encode(secret));
      const result = await request("/verify-email?token=" + expired + "&callbackURL=" + encodeURIComponent(baseURL + "/verify-email/callback"));
      assert.equal(result.status, 302); assert(new URL(result.headers.get("location")).searchParams.get("error"));
      const invalid = await request("/verify-email?token=invalid&callbackURL=" + encodeURIComponent(baseURL + "/verify-email/callback")); assert.equal(invalid.status, 302);
      assert.equal((await login("legacy-buyer@example.invalid", password)).json.user.emailVerified, false);
      assert.equal((await request("/send-verification-email", { email: "new@example.invalid" })).status, 200);
    });

    await t.test("concurrent PostgreSQL limiter enforces custom rules and keeps signin defaults", async () => {
      const tests = [["/request-password-reset", { email: "nobody@example.invalid" }, 3], ["/send-verification-email", { email: "nobody@example.invalid" }, 3], ["/reset-password", { token: "invalid", newPassword: password }, 10], ["/change-password", { currentPassword: "invalid", newPassword: password }, 5], ["/sign-in/email", { email: "nobody@example.invalid", password }, 3]];
      for (const [path, body, allowed] of tests) {
        const ip = `203.0.113.${++ipNumber % 250 + 1}`;
        const results = await Promise.all(Array.from({ length: allowed + 6 }, () => request(path, body, { ip })));
        assert.equal(results.filter(r => r.status !== 429).length, allowed, path);
        assert(results.filter(r => r.status === 429).every(r => Number(r.headers.get("X-Retry-After")) > 0));
      }
      assert(Number((await pool.query('SELECT count(*) FROM "rateLimit"')).rows[0].count) > 0);
    });
  } finally {
    await pool?.end();
    await setup.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
    await setup.end();
  }
});
